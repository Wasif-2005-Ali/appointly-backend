"""
call/consumers.py — WebSocket consumers for WebRTC signaling.

Two consumers are defined here:

1. CallConsumer  (ws://<host>/ws/call/<call_id>/)
   ─────────────────────────────────────────────
   Handles the full WebRTC signaling lifecycle for a single call:
   - Call initiation & ringing
   - Accept / reject / end
   - SDP offer / answer relay (point-to-point via channel name)
   - ICE candidate relay (point-to-point via channel name)
   - Connection state notifications

2. UserNotifyConsumer  (ws://<host>/ws/notify/)
   ──────────────────────────────────────────────
   Lightweight "presence" consumer.  Each authenticated user connects
   once per session and joins their personal ``user_<pk>`` group so that
   incoming call notifications (sent by the remote CallConsumer) reach
   them without polling.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Full signaling flow
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  CALLER                   SERVER                     CALLEE
  ──────                   ──────                     ──────
  connect ws/notify/  ───►  join user_<A> group
  connect ws/call/<id>/ ──► join call_<id> group
  call.initiate ──────────► create CallSession
                            group_send user_<B>  ────► call.incoming
                                                        (via UserNotifyConsumer)
                                                  CALLEE connects to ws/notify/
                                                  CALLEE connects to ws/call/<id>/
                                                        ◄── call.peer_joined (bidirectional)
                            call.accepted ◄─────── call.accept
  call.accepted ◄──────────
  ── RTCPeerConnection created ──
  call.sdp_offer ─────────► channel_layer.send()  ────► call.sdp_offer
                                                        ◄── call.sdp_answer
  call.sdp_answer ◄────────
  ─────────── ICE candidate exchange (parallel, both directions) ───────────
  call.ice_candidate ─────► channel_layer.send()  ────► call.ice_candidate
                                                   ◄─── call.ice_candidate
  call.ice_candidate ◄─────
  ─────────────────── P2P media flows directly (DTLS/SRTP) ────────────────
  call.end ───────────────► session.end()
                            group_send  ────────────────► call.ended
  call.ended ◄─────────────

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
WebSocket close codes
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  4001  —  Invalid or missing JWT
  4003  —  User is not a participant of this call
  4004  —  call_id not found (and user did not send call.initiate)
  4008  —  Call already in a terminal state
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Optional

from channels.db import database_sync_to_async
from channels.generic.websocket import AsyncJsonWebsocketConsumer

from .models import CallSession, CallStatus

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Shared JWT helper (identical pattern to chat/consumers.py)
# ---------------------------------------------------------------------------

def _get_user_from_token(token: str):
    """
    Validate a SimpleJWT access token and return the Django User,
    or None on any failure (expired, tampered, unknown user).
    """
    from rest_framework_simplejwt.tokens import AccessToken
    from rest_framework_simplejwt.exceptions import InvalidToken, TokenError
    from django.contrib.auth import get_user_model

    User = get_user_model()
    try:
        payload = AccessToken(token)
        return User.objects.get(pk=payload["user_id"])
    except (InvalidToken, TokenError, User.DoesNotExist, KeyError):
        return None


def _parse_qs(scope) -> dict[bytes, bytes]:
    """Parse ``?key=value&…`` query string from a Channels scope."""
    raw: bytes = scope.get("query_string", b"")
    return {
        k: v
        for pair in raw.split(b"&")
        if b"=" in pair
        for k, v in [pair.split(b"=", 1)]
    }


# ---------------------------------------------------------------------------
# 1.  CallConsumer
# ---------------------------------------------------------------------------

class CallConsumer(AsyncJsonWebsocketConsumer):
    """
    WebRTC signaling consumer for a single call session.

    URL  : ws://<host>/ws/call/<call_id>/
    Auth : ?token=<SimpleJWT access token>

    The ``call_id`` in the URL must be a 32-character UUID4 hex string
    generated by the caller before connecting.  The session document is
    created in MongoDB when the caller sends ``call.initiate``.
    """

    # ------------------------------------------------------------------
    # Frame-type → handler dispatch table
    # ------------------------------------------------------------------
    _HANDLERS = {
        "call.initiate":     "_handle_initiate",
        "call.accept":       "_handle_accept",
        "call.reject":       "_handle_reject",
        "call.end":          "_handle_end",
        "call.sdp_offer":    "_handle_sdp_offer",
        "call.sdp_answer":   "_handle_sdp_answer",
        "call.ice_candidate":"_handle_ice_candidate",
    }

    # ------------------------------------------------------------------
    # Connection lifecycle
    # ------------------------------------------------------------------

    async def connect(self) -> None:
        params = _parse_qs(self.scope)
        token  = params.get(b"token", b"").decode()

        # 1. Authenticate
        self.user = await database_sync_to_async(_get_user_from_token)(token)
        if self.user is None:
            await self.close(code=4001)
            return

        self.user_id: str = str(self.user.pk)
        self.call_id: str = self.scope["url_route"]["kwargs"]["call_id"]
        self.group_name: str = f"call_{self.call_id}"

        # 2. Optionally validate existing session
        #    (None is OK — caller will send call.initiate shortly)
        self.session: Optional[CallSession] = await database_sync_to_async(
            CallSession.get_by_call_id
        )(self.call_id)

        if self.session is not None:
            # Session exists — must be a participant
            if not self.session.is_participant(self.user_id):
                await self.close(code=4003)
                return
            # Already in a terminal state — reject new connections
            if self.session.is_terminal:
                await self.close(code=4008)
                return

        # 3. Join the call group and the personal user group
        await self.channel_layer.group_add(self.group_name, self.channel_name)
        await self.channel_layer.group_add(f"user_{self.user_id}", self.channel_name)

        # 4. Accept the socket
        await self.accept()

        # 5. Announce presence so the peer knows we joined
        await self.channel_layer.group_send(
            self.group_name,
            {
                "type":         "call.peer_joined",
                "user_id":      self.user_id,
                "username":     self.user.get_username(),
            },
        )

        logger.info(
            "Call WS connect: user=%s call_id=%s channel=%s",
            self.user_id, self.call_id, self.channel_name,
        )

    async def disconnect(self, close_code: int) -> None:
        if hasattr(self, "group_name"):
            await self.channel_layer.group_discard(self.group_name,          self.channel_name)
            await self.channel_layer.group_discard(f"user_{self.user_id}",   self.channel_name)

        logger.info(
            "Call WS disconnect: user=%s call_id=%s code=%s",
            getattr(self, "user_id",  "?"),
            getattr(self, "call_id",  "?"),
            close_code,
        )

    # ------------------------------------------------------------------
    # Receive from client
    # ------------------------------------------------------------------

    async def receive_json(self, content: dict, **kwargs) -> None:
        frame_type: str = content.get("type", "")
        handler_name = self._HANDLERS.get(frame_type)
        if handler_name:
            await getattr(self, handler_name)(content)
        else:
            await self._error("unknown_type", f"Unknown frame type: '{frame_type}'")

    # ------------------------------------------------------------------
    # Inbound signal handlers
    # ------------------------------------------------------------------

    async def _handle_initiate(self, content: dict) -> None:
        """
        Called by the **caller** immediately after connecting.

        Frame:
            {
                "type":      "call.initiate",
                "callee_id": "<django user PK>",
                "call_type": "video" | "audio"   (default: "video")
            }
        """
        if self.session is not None:
            await self._error("already_exists", "A session with this call_id already exists.")
            return

        callee_id: str  = str(content.get("callee_id", "")).strip()
        call_type: str  = content.get("call_type", "video")

        if not callee_id:
            await self._error("missing_callee", "'callee_id' is required.")
            return
        if callee_id == self.user_id:
            await self._error("self_call", "You cannot call yourself.")
            return
        if call_type not in {"audio", "video"}:
            call_type = "video"

        # Validate callee exists
        callee = await database_sync_to_async(
            self._get_user_by_id
        )(callee_id)
        if callee is None:
            await self._error("callee_not_found", f"User '{callee_id}' does not exist.")
            return

        # Create the session
        self.session = await database_sync_to_async(CallSession.create)(
            call_id=   self.call_id,
            caller_id= self.user_id,
            callee_id= callee_id,
            call_type= call_type,
        )

        # Confirm to caller
        await self.send_json({
            "type":    "call.initiated",
            "session": self.session.to_broadcast_dict(),
        })

        # Notify callee via their personal user group
        # (forwarded by UserNotifyConsumer → client)
        await self.channel_layer.group_send(
            f"user_{callee_id}",
            {
                "type":             "call.incoming",
                "call_id":          self.call_id,
                "caller_id":        self.user_id,
                "caller_username":  self.user.get_username(),
                "call_type":        call_type,
            },
        )
        logger.info(
            "Call initiated: %s -> %s  call_id=%s  type=%s",
            self.user_id, callee_id, self.call_id, call_type,
        )

    async def _handle_accept(self, content: dict) -> None:
        """
        Called by the **callee** to accept the call.

        Frame: { "type": "call.accept" }
        """
        if not await self._require_session():
            return
        if self.session.status != CallStatus.RINGING:
            await self._error("invalid_state", f"Cannot accept a call in '{self.session.status}' state.")
            return
        if self.user_id != self.session.callee_id:
            await self._error("forbidden", "Only the callee can accept the call.")
            return

        await database_sync_to_async(self.session.accept)()

        await self.channel_layer.group_send(
            self.group_name,
            {
                "type":    "call.accepted",
                "session": self.session.to_broadcast_dict(),
            },
        )
        logger.info("Call accepted: call_id=%s by user=%s", self.call_id, self.user_id)

    async def _handle_reject(self, content: dict) -> None:
        """
        Called by the **callee** to decline the call.

        Frame: { "type": "call.reject" }
        """
        if not await self._require_session():
            return
        if self.session.status != CallStatus.RINGING:
            await self._error("invalid_state", f"Cannot reject a call in '{self.session.status}' state.")
            return
        if self.user_id != self.session.callee_id:
            await self._error("forbidden", "Only the callee can reject the call.")
            return

        await database_sync_to_async(self.session.reject)()

        await self.channel_layer.group_send(
            self.group_name,
            {
                "type":    "call.rejected",
                "session": self.session.to_broadcast_dict(),
            },
        )
        logger.info("Call rejected: call_id=%s by user=%s", self.call_id, self.user_id)

    async def _handle_end(self, content: dict) -> None:
        """
        Called by **either party** to terminate the call.

        Frame: { "type": "call.end" }
        """
        if not await self._require_session():
            return
        if self.session.is_terminal:
            await self._error("already_ended", "This call has already ended.")
            return
        if not self.session.is_participant(self.user_id):
            await self._error("forbidden", "You are not a participant of this call.")
            return

        await database_sync_to_async(self.session.end)()

        await self.channel_layer.group_send(
            self.group_name,
            {
                "type":    "call.ended",
                "session": self.session.to_broadcast_dict(),
                "ended_by": self.user_id,
            },
        )
        logger.info(
            "Call ended: call_id=%s by user=%s  duration=%.1fs",
            self.call_id, self.user_id,
            self.session.duration_seconds or 0,
        )

    # ------------------------------------------------------------------
    # WebRTC signal relay — point-to-point (caller ↔ callee only)
    # SDP and ICE messages are sent directly to the peer's channel,
    # NOT broadcast to the whole group, to avoid the sender receiving
    # their own signals.
    # ------------------------------------------------------------------

    async def _handle_sdp_offer(self, content: dict) -> None:
        """
        Relay an SDP offer from the caller to the callee.

        Frame:
            {
                "type": "call.sdp_offer",
                "sdp":  { "type": "offer", "sdp": "<SDP string>" }
            }
        """
        if not await self._require_session():
            return
        if not await self._require_connected_state():
            return
        if self.user_id != self.session.caller_id:
            await self._error("forbidden", "Only the caller sends the SDP offer.")
            return

        await self._relay_to_peer({
            "type":      "call.sdp_offer",
            "sdp":       content.get("sdp"),
            "sender_id": self.user_id,
        })

    async def _handle_sdp_answer(self, content: dict) -> None:
        """
        Relay an SDP answer from the callee to the caller.

        Frame:
            {
                "type": "call.sdp_answer",
                "sdp":  { "type": "answer", "sdp": "<SDP string>" }
            }
        """
        if not await self._require_session():
            return
        if not await self._require_connected_state():
            return
        if self.user_id != self.session.callee_id:
            await self._error("forbidden", "Only the callee sends the SDP answer.")
            return

        await self._relay_to_peer({
            "type":      "call.sdp_answer",
            "sdp":       content.get("sdp"),
            "sender_id": self.user_id,
        })

    async def _handle_ice_candidate(self, content: dict) -> None:
        """
        Relay an ICE candidate from either party to the other.

        Frame:
            {
                "type":      "call.ice_candidate",
                "candidate": {
                    "candidate":     "candidate:...",
                    "sdpMid":        "0",
                    "sdpMLineIndex": 0
                }
            }
        """
        if not await self._require_session():
            return
        if not await self._require_connected_state():
            return

        await self._relay_to_peer({
            "type":      "call.ice_candidate",
            "candidate": content.get("candidate"),
            "sender_id": self.user_id,
        })

    # ------------------------------------------------------------------
    # Group event handlers  (Channels maps "call.X" → "call_X")
    # ------------------------------------------------------------------

    async def call_peer_joined(self, event: dict) -> None:
        """Another consumer has joined the call group."""
        if event["user_id"] == self.user_id:
            return   # Our own announcement — ignore

        await self.send_json({
            "type":     "call.peer_connected",
            "user_id":  event["user_id"],
            "username": event["username"],
        })

    async def call_initiated(self, event: dict) -> None:
        if self.session:
            self.session.status = event["session"].get("status", self.session.status)
        await self.send_json(event)

    async def call_accepted(self, event: dict) -> None:
        if self.session:
            self.session.status = event["session"].get("status", self.session.status)
        await self.send_json(event)

    async def call_rejected(self, event: dict) -> None:
        if self.session:
            self.session.status = event["session"].get("status", self.session.status)
        await self.send_json(event)

    async def call_ended(self, event: dict) -> None:
        if self.session:
            self.session.status = event["session"].get("status", self.session.status)
        await self.send_json(event)

    async def call_sdp_offer(self, event: dict) -> None:
        """Forward a relayed SDP offer to the local client (ignore if from self)."""
        if event.get("sender_id") == self.user_id:
            return
        await self.send_json(event)

    async def call_sdp_answer(self, event: dict) -> None:
        """Forward a relayed SDP answer to the local client (ignore if from self)."""
        if event.get("sender_id") == self.user_id:
            return
        await self.send_json(event)

    async def call_ice_candidate(self, event: dict) -> None:
        """Forward a relayed ICE candidate to the local client (ignore if from self)."""
        if event.get("sender_id") == self.user_id:
            return
        await self.send_json(event)

    async def call_incoming(self, event: dict) -> None:
        """
        Forward an incoming-call notification to the local client.
        Triggered when someone calls this user while they're already
        connected to a call WS (e.g. they're in another call).
        """
        await self.send_json(event)

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    async def _relay_to_peer(self, event: dict) -> None:
        """Broadcast event to the group (consumers will ignore their own signals)."""
        await self.channel_layer.group_send(
            self.group_name,
            {
                **event,
            }
        )

    async def _require_session(self) -> bool:
        """Return True if a session exists; send an error frame and return False otherwise."""
        if self.session is None:
            await self._error("no_session", "No call session found. Send call.initiate first.")
            return False
        return True

    async def _require_connected_state(self) -> bool:
        """Return True if the session is in CONNECTED state; error otherwise."""
        if self.session.status != CallStatus.CONNECTED:
            await self._error(
                "not_connected",
                f"WebRTC signals can only be exchanged in 'connected' state "
                f"(current: '{self.session.status}').",
            )
            return False
        return True

    async def _error(self, code: str, detail: str) -> None:
        await self.send_json({"type": "error", "code": code, "detail": detail})

    @staticmethod
    def _get_user_by_id(user_id: str):
        from django.contrib.auth import get_user_model
        User = get_user_model()
        try:
            return User.objects.get(pk=user_id)
        except User.DoesNotExist:
            return None


# ---------------------------------------------------------------------------
# 2.  UserNotifyConsumer
# ---------------------------------------------------------------------------

class UserNotifyConsumer(AsyncJsonWebsocketConsumer):
    """
    Lightweight personal-notification consumer.

    URL  : ws://<host>/ws/notify/
    Auth : ?token=<SimpleJWT access token>

    Each authenticated user should maintain exactly ONE connection to
    this endpoint per browser/app session.  The consumer joins the
    ``user_<pk>`` channel group, which CallConsumer uses to push
    incoming-call notifications to an idle user.

    Frames sent to client
    ---------------------
        call.incoming  — someone is calling this user
            {
                "type":            "call.incoming",
                "call_id":         "...",
                "caller_id":       "...",
                "caller_username": "...",
                "call_type":       "video" | "audio"
            }
    """

    async def connect(self) -> None:
        params = _parse_qs(self.scope)
        token  = params.get(b"token", b"").decode()

        self.user = await database_sync_to_async(_get_user_from_token)(token)
        if self.user is None:
            await self.close(code=4001)
            return

        self.user_id: str   = str(self.user.pk)
        self.user_group: str = f"user_{self.user_id}"

        await self.channel_layer.group_add(self.user_group, self.channel_name)
        await self.accept()
        logger.info("Notify WS connect: user=%s channel=%s", self.user_id, self.channel_name)

    async def disconnect(self, close_code: int) -> None:
        if hasattr(self, "user_group"):
            await self.channel_layer.group_discard(self.user_group, self.channel_name)
        logger.info(
            "Notify WS disconnect: user=%s code=%s",
            getattr(self, "user_id", "?"), close_code,
        )

    async def receive_json(self, content: dict, **kwargs) -> None:
        """Clients do not send frames to this consumer."""
        await self.send_json({
            "type":   "error",
            "code":   "read_only",
            "detail": "This endpoint is read-only. No inbound frames are accepted.",
        })

    # ------------------------------------------------------------------
    # Group event handlers
    # ------------------------------------------------------------------

    async def call_incoming(self, event: dict) -> None:
        """Forward an incoming-call event to the connected client."""
        await self.send_json(event)
